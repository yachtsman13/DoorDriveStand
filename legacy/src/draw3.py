def sel(SS, keys=None, groups=None, box=None, exclude=()):
    out = []
    for key, name, shp, grp, col in SS.items:
        if key in exclude: continue
        if keys and key not in keys: continue
        if groups and grp not in groups: continue
        if box:
            bb = shp.BoundingBox(); (x0, y0, z0), (x1, y1, z1) = box
            if bb.xmax < x0 or bb.xmin > x1 or bb.ymax < y0 or bb.ymin > y1 or bb.zmax < z0 or bb.zmin > z1: continue
        out.append(shp)
    return compound(out)

def one(SS, key):
    for k, n, shp, g, c in SS.items:
        if k == key: return shp

def balloon(v, p, pos, dx, dy):
    a = v.T(p); t = a + np.array([dx, dy]); ax = v.sheet.ax
    ax.plot([a[0], t[0]], [a[1], t[1]], color='k', lw=0.2, zorder=6); ax.plot([a[0]], [a[1]], 'o', ms=1.3, color='k', zorder=6)
    ax.add_patch(plt.Circle(t, 2.6, fill=True, fc='white', ec='k', lw=0.3, zorder=6))
    ax.text(t[0], t[1], str(pos), ha='center', va='center', fontsize=6, zorder=7)

